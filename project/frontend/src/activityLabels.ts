export function activityLabel(activityId: string) {
  const generatedLesson = activityId.match(/^math6-bai(\d{2})-v01-quiz$/);
  if (generatedLesson) return "Toán 6 · Bài " + Number(generatedLesson[1]) + " · Kiểm tra tổng hợp";
  if (activityId === "math6-bai1-v054-kn1") return "Toán 6 · Bài 1 · Kiến thức nền 1";
  if (activityId === "math6-bai1-v054-kn2") return "Toán 6 · Bài 1 · Kiến thức nền 2";
  if (activityId === "math6-bai2-v01-tp") return "Toán 6 · Bài 2 · Hệ thập phân";
  if (activityId === "math6-bai2-v01-lm") return "Toán 6 · Bài 2 · Số La Mã";
  const vietnamese = activityId.match(/^vietnamese6-s[12]-(lesson\d+|review)-(trace|organize|infer|language|compose|communicate)$/);
  if (vietnamese) {
    const names: Record<string,string> = { trace:"Đọc theo dấu vết", organize:"Tổ chức văn bản", infer:"Suy luận có bằng chứng", language:"Thực hành tiếng Việt", compose:"Tạo lập văn bản", communicate:"Nói và nghe" };
    const branch = vietnamese[1] === "review" ? "Ôn tập" : `Bài ${vietnamese[1].replace("lesson", "")}`;
    return `Ngữ văn ${branch} · ${names[vietnamese[2]]}`;
  }
  const informatics = activityId.match(/^informatics6-s[12]-lesson(\d+)-(recognize|process|reason|diagnose|connect|safe-apply)$/);
  if (informatics) {
    const names: Record<string,string> = { recognize:"Nhận biết khái niệm", process:"Quy trình thao tác", reason:"Giải thích có căn cứ", diagnose:"Bắt lỗi số", connect:"Kết nối tình huống", "safe-apply":"Vận dụng an toàn" };
    return `Tin học Bài ${informatics[1]} · ${names[informatics[2]]}`;
  }
  const science = activityId.match(/^science6-l(\d+)-(observe-identify|classify-model|measure-analyze|predict-reason|experiment-safety|explain-apply)$/);
  if (science) {
    const names: Record<string,string> = { "observe-identify":"Quan sát và nhận biết", "classify-model":"Phân loại và mô hình hóa", "measure-analyze":"Đo và phân tích", "predict-reason":"Dự đoán và lập luận", "experiment-safety":"Thực nghiệm an toàn", "explain-apply":"Giải thích và vận dụng" };
    return `Khoa học tự nhiên Bài ${Number(science[1])} · ${names[science[2]]}`;
  }
  return LABELS[activityId] ?? activityId.replaceAll("-", " ");
}
